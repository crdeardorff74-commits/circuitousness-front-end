    const LANG_STORAGE_KEY = `${PROJECT_SLUG}_lang`;

    function detectLanguage() {
        const stored = localStorage.getItem(LANG_STORAGE_KEY);
        if (stored && SUPPORTED_LANGUAGES[stored]) return stored;
        const nav = (navigator.language || 'en').slice(0, 2).toLowerCase();
        return SUPPORTED_LANGUAGES[nav] ? nav : 'en';
    }

    function t(key, vars) {
        const dict = translations[currentLang] || translations.en;
        let s = dict[key];
        if (s === undefined) s = (translations.en && translations.en[key]) || key;
        if (vars && typeof s === 'string') {
            for (const k in vars) s = s.replace(new RegExp('\\{' + k + '\\}', 'g'), vars[k]);
        }
        return s;
    }

    function applyTranslations(root) {
        const scope = root || document;
        scope.querySelectorAll('[data-i18n]').forEach((el) => {
            const key = el.getAttribute('data-i18n');
            const text = t(key);
            if (text !== undefined) el.innerHTML = text;
        });
        scope.querySelectorAll('[data-i18n-attr]').forEach((el) => {
            // format: "attr:key,attr2:key2"
            const spec = el.getAttribute('data-i18n-attr');
            spec.split(',').forEach((pair) => {
                const [attr, key] = pair.split(':').map((s) => s.trim());
                if (attr && key) el.setAttribute(attr, t(key));
            });
        });
    }

    function setLanguage(lang) {
        if (!SUPPORTED_LANGUAGES[lang]) return;
        currentLang = lang;
        localStorage.setItem(LANG_STORAGE_KEY, lang);
        document.documentElement.setAttribute('lang', lang);
        applyTranslations();
    }

    function getLanguage() { return currentLang; }
    function getSupportedLanguages() { return SUPPORTED_LANGUAGES; }

    function init() {
        currentLang = detectLanguage();
        document.documentElement.setAttribute('lang', currentLang);
        applyTranslations();
    }

    return { init, t, applyTranslations, setLanguage, getLanguage, getSupportedLanguages };
